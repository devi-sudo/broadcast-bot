const TelegramBot = require("node-telegram-bot-api");
require("dotenv").config();

// Bot configurations
const botConfigs = [
  {
    token: process.env.BOT_TOKEN_1,
    username: process.env.BOT_USERNAME_1,
    name: "Bot 1"
  },
  {
    token: process.env.BOT_TOKEN_2,
    username: process.env.BOT_USERNAME_2,
    name: "Bot 2"
  }
];

const OWNER_ID = parseInt(process.env.OWNER_ID);


// Store data for each bot
const bots = [];
const botData = {};

// Initialize both bots
botConfigs.forEach((config, index) => {
  try {
    const bot = new TelegramBot(config.token, { polling: true });
    bots.push(bot);
    
    // Initialize data for this bot
    botData[config.token] = {
      name: config.name,
      username: config.username,
      postContent: null,
      spamInterval: null,
      awaitingLoopTime: {},
      groups: {},
      groupManagementState: {}
    };
    
    console.log(`✅all started`);
    
    // Set up all handlers for this bot
    setupBotHandlers(bot, config.token);
    
  } catch (error) {
    console.error(`❌ Failed to start ${config.name}:`, error);
  }
});

// -------------------- Group Management Functions --------------------

function saveGroups(botToken) {
  console.log(`${botData[botToken].name} Groups updated:`, botData[botToken].groups);
}

function addGroup(botToken, chatId, title) {
  botData[botToken].groups[chatId] = title;
  saveGroups(botToken);
  return `✅ Group added to ${botData[botToken].name}: ${title} (${chatId})`;
}

function removeGroup(botToken, chatId) {
  const groupName = botData[botToken].groups[chatId];
  delete botData[botToken].groups[chatId];
  saveGroups(botToken);
  return groupName ? `❌ Group removed from ${botData[botToken].name}: ${groupName} (${chatId})` : "Group not found!";
}

function listGroups(botToken) {
  const groups = botData[botToken].groups;
  if (Object.keys(groups).length === 0) {
    return `No groups added yet to ${botData[botToken].name}! Use /addgroup to add groups.`;
  }
  
  return Object.entries(groups)
    .map(([id, name], index) => `${index + 1}. ${name} — \`${id}\``)
    .join("\n");
}

// -------------------- Simple Chat Response System --------------------

function getChatResponse(message) {
  const lowerMsg = message.toLowerCase().trim();
  
  for (const [category, data] of Object.entries(chatData)) {
    if (category === 'default') continue;
    
    for (const pattern of data.patterns) {
      if (lowerMsg.includes(pattern)) {
        return data.responses[Math.floor(Math.random() * data.responses.length)];
      }
    }
  }
  
  return chatData.default.responses[Math.floor(Math.random() * chatData.default.responses.length)];
}

// -------------------- Bot Setup Function --------------------

function setupBotHandlers(bot, botToken) {
  const botName = botData[botToken].name;
  const botUsername = botData[botToken].username;

  // -------------------- Commands --------------------

  // Start command for everyone
  bot.onText(/^\/start$/, (msg) => {
    const chatId = msg.chat.id;
    const userId = msg.from.id;
    
    // Automatically add supergroup to groups list when ANY user sends /start
    if ((msg.chat.type === "group" || msg.chat.type === "supergroup") && !botData[botToken].groups[chatId]) {
      botData[botToken].groups[chatId] = msg.chat.title || "Unnamed Group";
      saveGroups(botToken);
      
      // Notify owner about the new group
      bot.sendMessage(OWNER_ID, `🤖 ${botName}: New group automatically added via /start:\n${botData[botToken].groups[chatId]} (${chatId})\nAdded by: ${msg.from.first_name} (@${msg.from.username || 'no username'})`);
      
      // Send welcome message to the group
      bot.sendMessage(chatId, `Hello ${msg.chat.title}! 👋\n\nI'm ${botName} here to chat with everyone! Feel free to talk to me! 😊`);
    }
    
    if (userId === OWNER_ID) {
      const ownerMenu = `🤖 ${botName} - Owner Mode Activated!\n\n📋 Available Commands:\n/createpost - Create new post\n/spam - Start broadcasting\n/stop - Stop broadcasting\n/groups - List all groups\n/addgroup - Add new group\n/removegroup - Remove a group\n/cleargroups - Remove all groups`;
      bot.sendMessage(chatId, ownerMenu);
    } else {
      // Private chat with regular user
      if (msg.chat.type === "private") {
        const welcomeMessage = `Hello ${msg.from.first_name}! \n\nI'm ${botName}, kya ham baat kr sakte he!😊`;
        
        // Create inline keyboard with button to add bot to group
        const replyMarkup = {
          reply_markup: {
            inline_keyboard: [
              [{
                text: `➕ Add ${botName} to your group`,
                url: `https://t.me/${botUsername}?startgroup=start`
              }]
            ]
          }
        };
        
        bot.sendMessage(chatId, welcomeMessage, replyMarkup);
      }
    }
  });

  // -------------------- Group Management Commands --------------------

  // Add group command
  bot.onText(/^\/addgroup$/, (msg) => {
    if (msg.from.id !== OWNER_ID) return;
    
    botData[botToken].groupManagementState[msg.chat.id] = { action: 'add_group' };
    bot.sendMessage(msg.chat.id, `➕ Please send the group ID you want to add to ${botName} (e.g., -1001234567890):`);
  });

  // Remove group command
  bot.onText(/^\/removegroup$/, (msg) => {
    if (msg.from.id !== OWNER_ID) return;
    
    if (Object.keys(botData[botToken].groups).length === 0) {
      return bot.sendMessage(msg.chat.id, `❌ No groups to remove from ${botName}! Use /addgroup first.`);
    }
    
    botData[botToken].groupManagementState[msg.chat.id] = { action: 'remove_group' };
    bot.sendMessage(msg.chat.id, `➖ Please send the group ID you want to remove from ${botName}:\n\n` + listGroups(botToken));
  });

  // Clear all groups command
  bot.onText(/^\/cleargroups$/, (msg) => {
    if (msg.from.id !== OWNER_ID) return;
    
    if (Object.keys(botData[botToken].groups).length === 0) {
      return bot.sendMessage(msg.chat.id, `❌ No groups to clear from ${botName}!`);
    }
    
    const groupCount = Object.keys(botData[botToken].groups).length;
    botData[botToken].groups = {};
    saveGroups(botToken);
    bot.sendMessage(msg.chat.id, `🗑️ Cleared all ${groupCount} groups from ${botName}!`);
  });

  // List groups command
  bot.onText(/^\/groups$/, (msg) => {
    if (msg.from.id !== OWNER_ID) return;
    
    const groupList = listGroups(botToken);
    bot.sendMessage(msg.chat.id, `👥 ${botName} Groups List:\n\n${groupList}`, {
      parse_mode: "Markdown"
    });
  });

  // -------------------- Message Handling --------------------

  bot.on("message", async (msg) => {
    const chatId = msg.chat.id;
    const userId = msg.from.id;
    const text = msg.text || "";
    
    // Handle group management first
    if (userId === OWNER_ID && botData[botToken].groupManagementState[chatId]) {
      const state = botData[botToken].groupManagementState[chatId];
      
      if (state.action === 'add_group') {
        const groupId = text.trim();
        
        // Validate group ID format
        if (!groupId.startsWith('-100') || isNaN(groupId)) {
          delete botData[botToken].groupManagementState[chatId];
          return bot.sendMessage(chatId, "❌ Invalid group ID format! Group ID should start with -100 and be a number.");
        }
        
        // Ask for group name
        botData[botToken].groupManagementState[chatId] = { 
          action: 'add_group_name', 
          groupId: groupId 
        };
        return bot.sendMessage(chatId, "📝 Now please send the group name:");
      }
      
      if (state.action === 'add_group_name') {
        const groupName = text.trim();
        const result = addGroup(botToken, botData[botToken].groupManagementState[chatId].groupId, groupName);
        delete botData[botToken].groupManagementState[chatId];
        return bot.sendMessage(chatId, result);
      }
      
      if (state.action === 'remove_group') {
        const groupId = text.trim();
        
        if (botData[botToken].groups[groupId]) {
          const result = removeGroup(botToken, groupId);
          delete botData[botToken].groupManagementState[chatId];
          return bot.sendMessage(chatId, result);
        } else {
          delete botData[botToken].groupManagementState[chatId];
          return bot.sendMessage(chatId, "❌ Group not found! Use /groups to see available groups.");
        }
      }
    }
    
    // Skip commands and owner admin messages
    if (text.startsWith("/")) {
      if (userId === OWNER_ID) {
        handleOwnerMessage(bot, botToken, msg);
      }
      return;
    }
    
    // Handle regular users in private chats
    if (msg.chat.type === "private" && userId !== OWNER_ID) {
      await bot.sendChatAction(chatId, "typing");
      
      setTimeout(() => {
        const response = getChatResponse(text);
        bot.sendMessage(chatId, response);
      }, 1000 + Math.random() * 1000);
    }
    
    // Handle owner messages for post creation
    if (userId === OWNER_ID && text && !text.startsWith("/")) {
      handleOwnerMessage(bot, botToken, msg);
    }
  });

  // -------------------- Owner Message Handling --------------------

  function handleOwnerMessage(bot, botToken, msg) {
    const chatId = msg.chat.id;
    const text = msg.text || "";

    // Register groups automatically if owner sends message in a group
    if ((msg.chat.type === "group" || msg.chat.type === "supergroup") && !botData[botToken].groups[chatId]) {
      botData[botToken].groups[chatId] = msg.chat.title || "Unnamed Group";
      bot.sendMessage(chatId, `Hello\n ${botData[botToken].groups[chatId]} \n\n👉😘`);
      saveGroups(botToken);
      return;
    }

    // If user is setting loop time
    if (botData[botToken].awaitingLoopTime[chatId]) {
      const seconds = parseInt(text);
      if (isNaN(seconds)) {
        return bot.sendMessage(chatId, "❌ Invalid time. Please send a number in seconds.");
      }

      botData[botToken].spamInterval = setInterval(() => deliverPost(bot, botToken, chatId, botData[botToken].postContent), seconds * 1000);
      bot.sendMessage(chatId, `🔁 ${botData[botToken].name} Loop started every ${seconds}s. Use /stop to stop.`);
      botData[botToken].awaitingLoopTime[chatId] = false;
      return;
    }

    // Save post content with formatting
    if (text && !text.startsWith("/")) {
      botData[botToken].postContent = {
        text: text,
        entities: msg.entities || [],
      };

      bot.sendMessage(chatId, `📝 ${botData[botToken].name} *Preview:*\n\n` + text, {
        parse_mode: "Markdown",
        reply_markup: {
          inline_keyboard: [
            [{ text: "✅ Broadcast Now", callback_data: "broadcast" }],
            [{ text: "🕒 Set Timer Loop", callback_data: "setloop" }],
            [{ text: "🗑 Cancel", callback_data: "cancel" }],
          ],
        },
      });
    }
  }

  // -------------------- Owner Commands --------------------

  bot.onText(/^\/createpost$/, (msg) => {
    if (msg.from.id !== OWNER_ID) return;
    botData[botToken].postContent = null;
    bot.sendMessage(msg.chat.id, `✍️ Send the formatted post content for ${botName} (bold, links, etc).`);
  });

  bot.onText(/^\/spam$/, (msg) => {
    if (msg.from.id !== OWNER_ID || !botData[botToken].postContent) return;
    if (Object.keys(botData[botToken].groups).length === 0) {
      return bot.sendMessage(msg.chat.id, `❌ No groups added to ${botName}! Use /addgroup first.`);
    }
    if (botData[botToken].spamInterval) return bot.sendMessage(msg.chat.id, `⚠️ ${botName} spam already running.`);
    botData[botToken].spamInterval = setInterval(() => deliverPost(bot, botToken, msg.chat.id, botData[botToken].postContent), 60000);
    bot.sendMessage(msg.chat.id, `✅ ${botName} spam started (every 60s).`);
  });

  bot.onText(/^\/stop$/, (msg) => {
    if (msg.from.id !== OWNER_ID) return;
    if (botData[botToken].spamInterval) {
      clearInterval(botData[botToken].spamInterval);
      botData[botToken].spamInterval = null;
      bot.sendMessage(msg.chat.id, `🛑 ${botName} spam stopped.`);
    } else {
      bot.sendMessage(msg.chat.id, `⚠️ No spam loop running for ${botName}.`);
    }
  });

  // -------------------- Callback Query Handling --------------------

  bot.on("callback_query", async (query) => {
    const chatId = query.message.chat.id;
    const data = query.data;
    
    await bot.answerCallbackQuery(query.id);
    
    if (!botData[botToken].postContent) return;

    if (data === "cancel") {
      botData[botToken].postContent = null;
      return bot.editMessageText(`❌ ${botData[botToken].name} post canceled.`, {
        chat_id: chatId,
        message_id: query.message.message_id,
      });
    }

    if (data === "broadcast") {
      if (Object.keys(botData[botToken].groups).length === 0) {
        return bot.sendMessage(chatId, `❌ No groups added to ${botData[botToken].name}! Use /addgroup first.`);
      }
      
      await bot.editMessageText(`🚀 ${botData[botToken].name} Broadcasting...`, {
        chat_id: chatId,
        message_id: query.message.message_id,
      });
      await deliverPost(bot, botToken, chatId, botData[botToken].postContent);
    }

    if (data === "setloop") {
      if (botData[botToken].spamInterval) {
        return bot.sendMessage(chatId, `⚠️ ${botData[botToken].name} loop already running. Use /stop to stop.`);
      }
      if (Object.keys(botData[botToken].groups).length === 0) {
        return bot.sendMessage(chatId, `❌ No groups added to ${botData[botToken].name}! Use /addgroup first.`);
      }
      bot.sendMessage(chatId, `⏱ Send time in seconds for ${botData[botToken].name} repeating spam:`);
      botData[botToken].awaitingLoopTime[chatId] = true;
    }
  });

  // -------------------- Delivery Logic --------------------

  async function deliverPost(bot, botToken, ownerChatId, post) {
    if (Object.keys(botData[botToken].groups).length === 0) {
      return bot.sendMessage(ownerChatId, `❌ No groups to broadcast to in ${botData[botToken].name}! Use /addgroup first.`);
    }
    
    let report = "";
    let successCount = 0;
    let failCount = 0;

    for (const [chatId, title] of Object.entries(botData[botToken].groups)) {
      try {
        await bot.sendMessage(chatId, post.text, {
          entities: post.entities,
        });
        report += `✅ *${title}* \`(${chatId})\`\n`;
        successCount++;
      } catch (e) {
        report += `❌ *${title}* \`(${chatId})\`\n`;
        failCount++;
      }
    }

    const maxLength = 4000;
    if (report.length > maxLength) {
      const lines = report.split('\n');
      let currentChunk = '';
      let partNumber = 1;
      const totalParts = Math.ceil(report.length / maxLength);
      
      for (const line of lines) {
        if ((currentChunk + line + '\n').length > maxLength && currentChunk !== '') {
          await bot.sendMessage(ownerChatId, `📦 ${botData[botToken].name} *Delivery Report (Part ${partNumber}/${totalParts}):*\n\n${currentChunk}`, {
            parse_mode: "Markdown",
          });
          currentChunk = line + '\n';
          partNumber++;
        } else {
          currentChunk += line + '\n';
        }
      }
      
      if (currentChunk) {
        await bot.sendMessage(ownerChatId, `📦 ${botData[botToken].name} *Delivery Report (Part ${partNumber}/${totalParts}):*\n\n${currentChunk}`, {
          parse_mode: "Markdown",
        });
      }
    } else {
      await bot.sendMessage(ownerChatId, `📦 ${botData[botToken].name} *Delivery Report:*\n\n${report}`, {
        parse_mode: "Markdown",
      });
    }

    await bot.sendMessage(ownerChatId, `📊 ${botData[botToken].name} *Summary:* ✅ ${successCount} successful, ❌ ${failCount} failed`);
  }
}

